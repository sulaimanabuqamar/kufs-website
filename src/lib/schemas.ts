/**
 * Schemas for everything under /content.
 *
 * These are the contract between whoever edits the content files (a team
 * member, not necessarily a developer) and the components that render them.
 * They are evaluated at build time and throw on the first invalid record, so
 * a malformed sponsor entry fails `pnpm build` loudly rather than shipping a
 * broken sponsor strip to a paying sponsor.
 */

/* -------------------------------------------------------------------------
   Shared primitives
   ------------------------------------------------------------------------- */

/** A path under /public, e.g. "/sponsors/apex-composites.webp". */
const publicPath = z
  .string()
  .regex(
    /^\/[^\s]*$/,
    "must be a root-relative path under /public, e.g. /sponsors/x.webp",
  );

/**
 * A social profile URL — absolute, and stripped of everything after the path.
 *
 * WHY THE QUERY STRING IS REJECTED RATHER THAN TRIMMED
 *
 * "Copy link" in the Instagram and LinkedIn apps appends a share-tracking
 * identifier to the URL — `?igsi=...` on Instagram, `?trk=`/`?originalSubdomain=`
 * on LinkedIn. That identifier is generated by, and tied to, the phone that
 * copied it. Publishing it puts one team member's tracking token in the footer
 * of every page on the site, forever, for every visitor to send back.
 *
 * The URL without it resolves to exactly the same profile, so the parameter is
 * never load-bearing. It is REJECTED rather than silently stripped because the
 * editor who pasted it should learn that the link they copied carries something
 * personal — a silent fix teaches nobody and hides the next one.
 *
 * A fragment is refused on the same grounds: it addresses a position inside a
 * page, which a profile link has no use for.
 */
const socialUrl = z
  .string()
  .url("must be a full URL including https://")
  .refine((v) => v.startsWith("https://"), "must start with https://")
  .refine(
    (v) => !/[?#]/.test(v),
    "must not carry a query string or fragment — you have most likely pasted a " +
      'share link ("Copy link" in the app). Everything from the "?" or "#" ' +
      "onwards is a tracking identifier for the device that copied it; delete " +
      "it and keep the bare profile URL.",
  );

/** An ISO calendar date, e.g. "2026-03-14". */
const isoDate = z
  .string()
  .regex(/^\d{4}-\d{2}-\d{2}$/, "must be an ISO date (YYYY-MM-DD)")
  .refine((v) => !Number.isNaN(Date.parse(v)), "must be a real calendar date");

/** Image dimensions are mandatory: every image on this site goes through
 *  next/image with explicit width/height so nothing shifts during load. */
const imageRef = z.object({
  src: publicPath,
  width: z.number().int().positive(),
  height: z.number().int().positive(),
  alt: z
    .string()
    .min(1, "alt text is required — describe the image, do not repeat the name"),
});

export type ImageRef = z.infer<typeof imageRef>;

