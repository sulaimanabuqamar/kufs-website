/**
 * Organisations we are affiliated with: the university, the competition, its
 * organiser.
 *
 * THIS IS NOT THE SPONSOR LIST, AND THE RULES ARE NOT THE SAME. A sponsor
 * gives us their logo and asks us to display it. These are third-party
 * trademarks used without a commercial relationship, and Formula Student and
 * IMechE both publish competitor branding guidance that limits when a team may
 * display the event marks and in what form. Stating that we compete is
 * generally fine; using the logo is more constrained.
 *
 * So every entry carries `permissionConfirmed`, and NOTHING RENDERS WITHOUT
 * IT. The flag is not decorative and it is not a to-do marker: it is the
 * render condition, checked in `getAffiliations()`, and it defaults to nothing
 * — there is no default value that could let an entry through by omission.
 *
 * The second condition is that the logo file actually exists. Permission to
 * use a mark is not the same as having been given the correct artwork, and a
 * logo pulled off a search result is neither the right asset nor licensed.
 * Khalifa University is the live example: permission is confirmed, the file
 * has not been supplied, and the entry therefore does not render.
 */
export const affiliationSchema = z.object({
  name: z.string().min(1),
  /**
   * Whether the organisation has confirmed we may display their mark.
   *
   * Required, with no default. Adding an entry is a deliberate act and so is
   * asserting this, and a boolean that defaults to `false` invites the reading
   * that leaving it out is the same as saying no — it is not, it is saying
   * nothing, and this file should not be able to say nothing about permission.
   */
  permissionConfirmed: z.boolean(),
  /**
   * The supplied artwork. `null` until the organisation sends the file.
   *
   * DO NOT point this at a logo downloaded from a search result or lifted off
   * the organisation's website. Universities in particular usually issue a
   * specific lockup for student organisations, which is not the plain
   * university mark — the version supplied matters.
   */
  logo: imageRef.nullish().default(null),
  /** Their site. Shown as a link on the logo. */
  url: z.string().url(),
  /** One short line on what the relationship actually is. */
  relationship: z.string().min(1),
  /**
   * What is still outstanding before this entry can render, in plain words.
   * Never shown on the site — it is read by whoever picks this up next, and it
   * is surfaced by `pnpm check:brand`.
   */
  pending: z.string().min(1).nullable().default(null),
});

export const affiliationsSchema = z
