#!/usr/bin/env node
/**
 * Keeps the TinaCMS admin honest about the Zod schemas.
 *
 *   pnpm check:tina
 *
 * The Tina fields are COMPILED from src/lib/schemas.ts by tina/zod-to-tina.ts,
 * so the usual failure mode — two hand-written schemas drifting apart — cannot
 * happen here. What this checks is the two things that still can:
 *
 * 1. THE COMPILER STILL HANDLES EVERY SCHEMA. It throws rather than guesses,
 *    so a new Zod construct fails here with the field path named, instead of
 *    at `tinacms build` time on a Vercel deploy, or worse, as a field that
 *    quietly stopped being editable.
 *
 * 2. THE UI OVERLAY STILL POINTS AT REAL FIELDS. tina/config.ts carries labels
 *    and help text keyed by dotted field path. Those cannot add or remove a
 *    field, but they CAN go stale: rename `blurb` in schemas.ts and its help
 *    text silently stops appearing. Every overlay key must resolve.
 *
 * It also writes a snapshot of the generated field tree to
 * scripts/data/tina-fields.json, which is committed. A change to a Zod schema
 * then shows up in review as a diff of what editors will see — which is the
 * question a reviewer actually wants answered.
 *
 * Run with --update to regenerate the snapshot after an intentional change.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { parseArgs } from "node:util";

import { createJiti } from "jiti";

const { values: argv } = parseArgs({
  options: { update: { type: "boolean", default: false } },
  allowPositionals: true,
});

const SNAPSHOT = "scripts/data/tina-fields.json";

const jiti = createJiti(`${process.cwd()}/`, {
  alias: { "@": `${process.cwd()}/src` },
});

const { fieldsFromZod, fieldPaths } = await jiti.import("./tina/zod-to-tina.ts");
const schemas = await jiti.import("./src/lib/schemas.ts");
const overlays = await jiti.import("./tina/overlays.ts");

/** Collection name -> [Zod schema, overlay]. Mirrors tina/config.ts. */
const COPY_PAGES = [
  "common",
  "home",
  "become-a-sponsor",
  "sponsors",
  "team",
  "the-car",
  "progress",
  "news",
  "join",
  "press-kit",
  "contact",
  "not-found",
];

/** Copy overlays are exported as <camelCasePage>CopyOverlay. */
const copyOverlayName = (page) =>
  `${page.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}CopyOverlay`;

const COLLECTIONS = {
  site: [schemas.siteSchema, overlays.siteOverlay],
  sponsors: [schemas.sponsorSchema, overlays.sponsorOverlay],
  team: [schemas.teamMemberSchema, overlays.teamOverlay],
  tiers: [schemas.tierSchema, overlays.tierOverlay],
  milestones: [schemas.milestoneSchema, overlays.milestoneOverlay],
  roles: [schemas.roleSchema, overlays.roleOverlay],
  cars: [schemas.carSchema, overlays.carOverlay],
  news: [schemas.newsFrontmatterSchema, overlays.newsOverlay],
  ...Object.fromEntries(
    COPY_PAGES.map((page) => [
      `copy/${page}`,
      [schemas.COPY_SCHEMAS[page], overlays[copyOverlayName(page)]],
    ]),
  ),
};

console.log("TinaCMS schema check\n");

const failures = [];
const snapshot = {};

for (const [name, [schema, overlay]] of Object.entries(COLLECTIONS)) {
  let fields;
  try {
    fields = fieldsFromZod(schema, overlay);
  } catch (error) {
    failures.push(`${name}: ${error.message}`);
    console.log(`  FAIL  ${name} — compiler refused`);
    continue;
  }

  const paths = new Set(fieldPaths(fields));
  snapshot[name] = [...paths].sort();

  // An overlay key that resolves to nothing is help text that has silently
  // stopped appearing — almost always because the Zod field was renamed.
  const stale = Object.keys(overlay).filter((key) => !paths.has(key));
  if (stale.length) {
    failures.push(
      `${name}: overlay keys do not match any generated field — ${stale.join(", ")}`,
    );
    console.log(
      `  FAIL  ${name} — ${stale.length} stale overlay key(s): ${stale.join(", ")}`,
    );
    continue;
  }

  console.log(
    `  ok    ${name} — ${paths.size} fields, ${Object.keys(overlay).length} annotated`,
  );
}

/* -------------------------------------------------------------------------
   Snapshot
   ------------------------------------------------------------------------- */

const serialised = `${JSON.stringify(
  {
    note: "Generated by pnpm check:tina from src/lib/schemas.ts. Committed so that a Zod schema change shows up in review as a diff of what editors will see. Do not edit by hand; run `node scripts/check-tina-schema.mjs --update`.",
    collections: snapshot,
  },
  null,
  2,
)}\n`;

if (argv.update) {
  writeFileSync(SNAPSHOT, serialised);
  console.log(`\n  Snapshot updated: ${SNAPSHOT}\n`);
} else if (!existsSync(SNAPSHOT)) {
  failures.push(`${SNAPSHOT} does not exist — run with --update to create it`);
} else if (
  // Compared as parsed data, not as text: the snapshot is written by this
  // script and then reformatted by Prettier, so a byte comparison would fail
  // forever on whitespace alone.
  JSON.stringify(JSON.parse(readFileSync(SNAPSHOT, "utf8")).collections) !==
  JSON.stringify(snapshot)
) {
  const previous = JSON.parse(readFileSync(SNAPSHOT, "utf8")).collections;
  console.log("\n  FAIL  the editable field set changed:\n");
  for (const [name, paths] of Object.entries(snapshot)) {
    const before = new Set(previous[name] ?? []);
    const after = new Set(paths);
    const added = [...after].filter((p) => !before.has(p));
    const removed = [...before].filter((p) => !after.has(p));
    if (added.length) console.log(`    ${name}  + ${added.join(", ")}`);
    if (removed.length) console.log(`    ${name}  - ${removed.join(", ")}`);
  }
  console.log(
    "\n  If that is intentional, run:  node scripts/check-tina-schema.mjs --update\n" +
      "  and commit the snapshot alongside the schema change.\n",
  );
  failures.push("field snapshot is out of date");
}

if (failures.length) {
  console.error(`\n${failures.length} problem(s):\n`);
  for (const failure of failures) console.error(`  • ${failure}\n`);
  process.exit(1);
}

console.log("\n  Tina fields match the Zod schemas.\n");
